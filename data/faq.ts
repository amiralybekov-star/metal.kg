import type { Faq } from './catalog';
import { ADDRESS, WORK_HOURS_TEXT } from './contacts';
import { FOUNDING_YEAR } from './site';

/**
 * Вопросы для главной и разметки FAQPage. Первая фраза ответа отвечает
 * сразу, так её проще процитировать поиску и ИИ-ассистентам.
 * Только то, что уже есть на сайте; цены берутся из каталога.
 */
export function homeFaq(prices: { washer?: number; bath?: number; foundation?: number }): Faq[] {
  return [
    {
      q: 'Где в Бишкеке купить анкерные шайбы и ванночки для сварки?',
      a: `У нас в цеху: ${ADDRESS.street}, ${ADDRESS.district.toLowerCase()}. Работаем ${WORK_HOURS_TEXT}. Ходовые размеры обычно есть на складе, но перед приездом позвоните, чтобы мы проверили наличие.`,
    },
    {
      q: 'Сколько стоят шайбы, ванночки и закладные?',
      a: [
        prices.washer ? `Шайбы АШ от ${prices.washer} сом за штуку.` : '',
        prices.bath ? `Ванночки от ${prices.bath} сом за штуку.` : '',
        prices.foundation ? `Закладные детали ${prices.foundation} сом за килограмм.` : '',
        'Это цены за наличные, по бартеру выходит дороже. Цена на каждый размер есть в прайсе.',
      ]
        .filter(Boolean)
        .join(' '),
    },
    {
      q: 'Сделаете деталь по моему чертежу?',
      a: 'Да. Анкерные болты, закладные, шайбы нестандартного размера и другие детали делаем по чертежу или эскизу. Пришлите его в WhatsApp, посчитаем цену и срок. Обычно на изготовление уходит от 1 до 5 дней.',
    },
    {
      q: 'Можно купить несколько штук, а не оптом?',
      a: 'Можно. Шайбы, ванночки и муфты продаём от одной штуки. Для объектов делаем оптовые партии.',
    },
    {
      q: 'Доставляете?',
      a: `Да, по Бишкеку и по Кыргызстану. Или забирайте сами со склада на ${ADDRESS.street.replace('Профсоюзная', 'Профсоюзной')}.`,
    },
    {
      q: 'Вы производитель или перепродаёте?',
      a: `Производитель. Цех и склад у нас свои, работаем с ${FOUNDING_YEAR} года, поэтому продаём без наценки перекупщиков.`,
    },
  ];
}
